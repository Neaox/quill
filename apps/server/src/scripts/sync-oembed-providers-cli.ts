import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

/**
 * Regenerates `infrastructure/link-preview/oembed-providers.gen.ts` from the
 * oembed.com registry (ADR-042): `pnpm --filter @quill/server oembed:sync`.
 *
 * The registry is **vendored and pinned**, never read at runtime: a runtime
 * dependency on a third-party list is both a privacy event and a way for that
 * list to change what our server fetches. A person runs this, reads the diff,
 * and commits it.
 *
 * Only what the resolver uses is kept: the URL schemes and the JSON endpoint of
 * each provider that offers one. A provider with no schemes (discovery-only) or
 * with only an XML endpoint (ADR-042 refuses XML) is dropped.
 */

const SOURCE = 'https://oembed.com/providers.json'
const OUTPUT = new URL('../infrastructure/link-preview/oembed-providers.gen.ts', import.meta.url)

interface RegistryEndpoint {
  readonly schemes?: readonly string[]
  readonly url: string
  readonly formats?: readonly string[]
}

interface RegistryProvider {
  readonly provider_name: string
  readonly endpoints: readonly RegistryEndpoint[]
}

const response = await fetch(SOURCE, { signal: AbortSignal.timeout(20_000) })
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`)
const text = await response.text()
const registry: readonly RegistryProvider[] = JSON.parse(text)

const providers = registry
  .flatMap((provider) =>
    provider.endpoints
      .filter(
        (endpoint) =>
          (endpoint.schemes?.length ?? 0) > 0 &&
          (endpoint.formats === undefined || endpoint.formats.includes('json')) &&
          endpoint.url.startsWith('https://'),
      )
      .map((endpoint) => ({
        name: provider.provider_name,
        endpoint: endpoint.url.replace('{format}', 'json'),
        schemes: endpoint.schemes ?? [],
      })),
  )
  .toSorted((a, b) => a.name.localeCompare(b.name) || a.endpoint.localeCompare(b.endpoint))

const digest = createHash('sha256').update(text).digest('hex')
const source = `// GENERATED by \`pnpm --filter @quill/server oembed:sync\`. Do not edit by hand.
// Source: ${SOURCE} (sha256 ${digest}), ${providers.length} endpoints.
import type { OembedProvider } from './oembed-registry.ts'

export const OEMBED_PROVIDERS: readonly OembedProvider[] = ${JSON.stringify(providers, null, 2)}
`
await writeFile(OUTPUT, source)
process.stdout.write(`Wrote ${providers.length} oEmbed endpoints to ${fileURLToPath(OUTPUT)}
`)
