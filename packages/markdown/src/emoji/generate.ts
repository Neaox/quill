/**
 * The source of `shortcodes.gen.ts`, from GitHub's own emoji list (ADR-038).
 *
 * `gemoji` is the list GitHub renders `:+1:` from, published as data. It is a
 * development dependency only: the generated table carries what the renderer
 * and the editor need — the character, its description, and its names — in
 * about a sixth of the package's size, and nothing of it is loaded at runtime.
 */

/** One emoji as `gemoji` describes it; only the fields the table keeps. */
export interface GemojiEntry {
  readonly emoji: string
  readonly description: string
  readonly names: readonly string[]
}

/** The command that writes the generated file, named in its header. */
export const GENERATE_COMMAND = 'pnpm --filter @quill/markdown generate:emoji'

/**
 * One line per emoji: the character, a tab, its description, a tab, and its
 * names separated by spaces. Neither a tab nor a newline occurs in any field,
 * so the table needs no escaping beyond what a template literal asks for.
 */
export function shortcodeTable(entries: readonly GemojiEntry[]): string {
  return entries
    .map((entry) => `${entry.emoji}\t${entry.description}\t${entry.names.join(' ')}`)
    .join('\n')
}

/** The generated module, header and all. */
export function shortcodeModule(entries: readonly GemojiEntry[]): string {
  const table = shortcodeTable(entries).replaceAll('\\', '\\\\').replaceAll('`', '\\`')
  return [
    `// Generated by \`${GENERATE_COMMAND}\` from the gemoji package. Do not edit.`,
    '',
    '/** GitHub’s emoji shortcodes: `character<TAB>description<TAB>names`, one emoji per line. */',
    `export const SHORTCODE_TABLE = \`${table}\``,
    '',
  ].join('\n')
}
