/** A fence with a backtick run longer than any inside the code, so the code cannot close it early. */
function fence(language: CodeLanguage, code: string): string {
  const longest = Math.max(2, ...[...code.matchAll(/`+/gu)].map((run) => run[0].length))
  const ticks = '`'.repeat(longest + 1)
  return [`## ${language.label}`, '', `${ticks}${language.id}`, code, ticks, ''].join('\n')
}

/** The corpus as one Markdown document: a heading and a block per language, in registry order. */
export function corpusDocument(): string {
  return [
    '# Code languages',
    '',
    'One block in every language the reader and the editor colour.',
    '',
    ...CODE_LANGUAGES.map((language) => fence(language, LANGUAGE_CORPUS[language.id])),
  ].join('\n')
}
