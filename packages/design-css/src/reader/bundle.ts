import { fileURLToPath } from 'node:url'

import { rolldown, type Plugin } from 'rolldown'

/** The command that rewrites `reader.gen.js`, named in its header (AGENTS.md rule 11a). */
export const REGENERATE_READER = 'pnpm --filter @quill/design-css generate:reader'

/** Where the generated script sits, beside its source. */
export const READER_SCRIPT_FILE = 'reader.gen.js'

/** The bundle's entry: no file on disk, just the one call that enhances the page. */
const ENTRY = '\0public-reader-entry'

const entry: Plugin = {
  name: 'public-reader-entry',
  resolveId: (id) => (id === ENTRY ? ENTRY : null),
  load: (id) =>
    id === ENTRY
      ? [
          `import { enhanceReader } from ${JSON.stringify(fileURLToPath(new URL('reader.ts', import.meta.url)))}`,
          'enhanceReader(window)',
        ].join('\n')
      : null,
}

/**
 * The public site's reader script: `reader.ts` and everything it imports —
 * the lightbox, `@quill/highlight`'s DOM-free client and its browser adapter —
 * as one minified ES module that enhances the page it is loaded into.
 *
 * The public site has no bundler at run time (ADR-023), and the highlight
 * client is several modules, so the bundling happens here, ahead of time,
 * with Rolldown, and the server serves the file it writes. Only the
 * range-painting client ships: no Prism grammar is reachable from the entry,
 * and the size test beside this file holds that. The output is deterministic,
 * so the same test regenerates it and fails if the committed copy has drifted
 * from its sources.
 */
export async function bundleReaderScript(): Promise<string> {
  const bundle = await rolldown({ input: ENTRY, platform: 'browser', plugins: [entry] })
  try {
    const {
      output: [{ code }],
    } = await bundle.generate({ format: 'esm', minify: true })
    return `// Generated by \`${REGENERATE_READER}\` from reader.ts. Do not edit.\n${code.trimEnd()}\n`
  } finally {
    await bundle.close()
  }
}
